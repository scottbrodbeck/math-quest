#!/usr/bin/env node
// Pre-records the spelling read-aloud clips with the Mac's built-in voice (macOS `say`),
// so every device hears the same voice with the same pacing.
//
//   node tools/make-audio.mjs                  make any clips that are missing
//   node tools/make-audio.mjs --force          remake every clip
//   node tools/make-audio.mjs --only=does,read remake just these words
//   node tools/make-audio.mjs --voice=Ava      use another installed voice (default: Samantha)
//
// Run it again after adding words to spelling-words.js. Output: audio/w/<word>.m4a (the word
// alone), audio/s/<word>.m4a (its sentence), audio/l/<letter>.m4a (letter names, for spelling
// words out), and audio/clips.js, which tells the app which clips exist. Words without a clip
// fall back to the device's own voice.

import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import vm from "node:vm";
import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT = path.join(ROOT, "audio");
const EXT = "m4a";   // AAC: small, and plays in Safari, Chrome, Edge and Firefox
// Letter names spelled the way they're said, so the voice never reads "a" as "uh".
const LETTER_SAY = {
  a: "ay", b: "bee", c: "see", d: "dee", e: "ee", f: "eff", g: "jee", h: "aitch", i: "eye",
  j: "jay", k: "kay", l: "ell", m: "em", n: "en", o: "oh", p: "pee", q: "cue", r: "are",
  s: "ess", t: "tee", u: "you", v: "vee", w: "double you", x: "ex", y: "why", z: "zee",
};
// How to say a word on its own if the voice gets it wrong (then rerun with --only=word).
const WORD_SAY = {};

const flags = process.argv.slice(2);
const flag = name => (flags.find(f => f.startsWith("--" + name + "=")) || "").split("=")[1];
const force = flags.includes("--force");
const only = (flag("only") || "").split(",").filter(Boolean);
const voice = flag("voice") || "Samantha";

if (process.platform !== "darwin") { console.error("This needs a Mac (it uses the built-in `say` voice)."); process.exit(1); }
const installed = execFileSync("say", ["-v", "?"], { encoding: "utf8" }).split("\n").map(l => l.split(/\s{2,}/)[0].trim());
if (installed.indexOf(voice) < 0) { console.error(`Voice "${voice}" isn't installed. Installed: ${installed.filter(Boolean).join(", ")}`); process.exit(1); }

const ctx = { window: {} };
vm.createContext(ctx);
vm.runInContext(fs.readFileSync(path.join(ROOT, "spelling-words.js"), "utf8"), ctx);
const words = [];
ctx.window.SPELLING_UNITS.forEach(u => u.words.forEach(line => {
  const p = line.split("|");
  words.push({ word: p[0], sentence: p[3] });
}));

const tmp = path.join(os.tmpdir(), "make-audio-" + process.pid + ".aiff");
function record(text, file) {
  if (!force && !only.length && fs.existsSync(file)) return false;
  fs.mkdirSync(path.dirname(file), { recursive: true });
  execFileSync("say", ["-v", voice, "-o", tmp, text]);
  execFileSync("afconvert", ["-f", "m4af", "-d", "aac", "-b", "48000", "-c", "1", tmp, file]);
  return true;
}

let made = 0;
words.forEach((w, i) => {
  if (only.length && only.indexOf(w.word) < 0) return;
  if (record((WORD_SAY[w.word] || w.word) + ".", path.join(OUT, "w", w.word + "." + EXT))) made++;
  if (record(w.sentence, path.join(OUT, "s", w.word + "." + EXT))) made++;
  if ((i + 1) % 50 === 0) console.log(`  ${i + 1}/${words.length} words`);
});
if (!only.length) Object.keys(LETTER_SAY).forEach(c => { if (record(LETTER_SAY[c] + ".", path.join(OUT, "l", c + "." + EXT))) made++; });
try { fs.unlinkSync(tmp); } catch (e) {}

// Index of which clips exist (a word counts only if both its clips do).
const has = sub => new Set(fs.existsSync(path.join(OUT, sub)) ? fs.readdirSync(path.join(OUT, sub)).filter(f => f.endsWith("." + EXT)).map(f => f.slice(0, -EXT.length - 1)) : []);
const w = has("w"), s = has("s"), l = has("l");
const index = {
  v: Date.now().toString(36),   // cache-buster: changes every run
  voice,
  ext: EXT,
  letters: Object.keys(LETTER_SAY).every(c => l.has(c)),
  words: words.map(x => x.word).filter(x => w.has(x) && s.has(x)),
};
fs.writeFileSync(path.join(OUT, "clips.js"),
  "// Generated by tools/make-audio.mjs — which pre-recorded spelling clips exist.\n" +
  "window.SPELLING_AUDIO = " + JSON.stringify(index) + ";\n");
console.log(`Made ${made} clips with ${voice}. ${index.words.length}/${words.length} words have clips; letters: ${index.letters ? "yes" : "no"}.`);
